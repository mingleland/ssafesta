-- 게임 파트가 축제장 1번 자리를 이벤트 부스로 쓰기로 했고(2026-09-10), 지금은 Unity 씬 설정에
-- "슬롯 1 = 이벤트 부스" 가 박혀 있다. 슬롯 번호가 바뀌는 날 그 하드코딩은 조용히 틀린다 —
-- 슬롯 목록이 이미 type 을 싣고 있으므로 서버가 말해 주면 클라이언트가 추측을 그만둘 수 있다.
--
-- 임대 차단은 이 한 줄로 끝난다. BoothSlot.isRentable() 이 USER_RENTAL 만 통과시키므로
-- (spec 004 FR-002) 새 검사를 어디에도 더하지 않는다. 1번 자리는 이제 임대 목록에서
-- BOOTH_SLOT_NOT_RENTABLE 로 거절된다.
--
-- slot_type 에 CHECK 제약이 없어(V1:32 VARCHAR(30)) 값 추가에 스키마 변경이 필요 없다.
--
-- ⚠️ 1번 슬롯에 ACTIVE 임대가 남아 있는 환경이면 그 임대는 만료까지 그대로 산다. 데이터가
-- 깨지지는 않는다 — 목록에 OCCUPIED 로 보이고, 만료 스윕도 그대로 돌며, 만료 뒤 재임대만
-- 거절된다. 조건부 UPDATE 로 만들지 않은 것은 의도다: 환경마다 결과가 달라지면 "슬롯 1 은
-- 이벤트다" 가 더 이상 계약이 아니게 된다.
--
-- 이벤트 콘텐츠 자체는 부스가 아니다. 경품 상점과 그 설문은 부스 밖에서 survey_key 로 찾는다
-- (GitLab #173) — 가짜 유저·임대·게시 레이아웃을 만들지 않으려는 것이고, 그중 하나가
-- 어긋나면 이벤트가 조용히 404 가 되기 때문이다. 이 표식은 자리의 종류만 말한다.
UPDATE booth_slots SET slot_type = 'EVENT' WHERE id = 1;
